# Índices para búsqueda rápida
_MUNICIPIOS_BY_CODE: dict[str, AdminDivision] = {m.code: m for m in _MUNICIPIOS}
_MUNICIPIOS_BY_STATE: dict[str, list[AdminDivision]] = {}
for m in _MUNICIPIOS:
    _MUNICIPIOS_BY_STATE.setdefault(m.parent_code or "", []).append(m)


def get_estados() -> list[AdminDivision]:
    return list(_ESTADOS)


def get_municipios(estado_code: str | None = None) -> list[AdminDivision]:
    if estado_code:
        return _MUNICIPIOS_BY_STATE.get(estado_code, [])
    return list(_MUNICIPIOS)


def find_municipio(code: str) -> AdminDivision | None:
    return _MUNICIPIOS_BY_CODE.get(code)


def search_municipios(query: str, limit: int = 10) -> list[AdminDivision]:
    q = query.lower().strip()
    if not q:
        return []
    results = [m for m in _MUNICIPIOS if q in m.name.lower()]
    return results[:limit]